// bug is a customizable markup language similar to Markdown, except it's a bit more consistent
// and easier-to-remember with its use of symbols
// (honestly, it's because I just hate markdown's url format symbols - i can never remember
// the right order...)
// All HTML formatting is done by wrapping text with special keyword characters.
// Text formatting is done using two identical characters.
// Special functions like creating a hyperlink or image with description use two sets of characters.

// the syntax file tags.bug contains all of the symbols used to replace tags
// this is where you customize them!

// all of the symbols and tags used in this script are
// defined in tags.bug, which is user-customizable.
$symbols = extract_bug_symbols();
extract($symbols);

// global variable for the file extension
$bug_file_extension = "bug";

// parser to replace text markup with html tags
// returns parsed html
function parse_bug_markup($text)
{
    // put all of the $tags generated by extract_bug_symbols
    // into the local scope
	// this allows $code, $pre to exist in this scope
	global $tags;
	extract($tags);

	$parsedOutput = "";

	// before any parsing can occur, all newline endings must be
	// converted to the current architecture's line ending
	$text = convertNewline($text);

    // handle tags that require special processing
    // like <pre> and <p> and <code>
    if (is_array($text))
	{
		$preformattedOpen = false;
		$paragraphOpen = false;
		$codeOpen = false;
		$blockquoteOpen = false;
		$forceCloseParagraph = false;

		// handle multi-line tags like <pre> and <p>
		foreach ($text as $line)
		{
			// before any tag parsing, we must handle any escapes
			$line = escapes_to_htmlnumerics($line);
			$noparseOpen = false;

			// single line no-parse tag
			$detectNoparseTag = extract_text_from_tags($line, $noparse[2], $noparse[3]);
			$detectNoparseTagOpen = tag_exists($line, $noparse[2]);
			$detectNoparseTagClose = tag_exists($line, $noparse[3]);

			// when "noparse" tag has been detected, we skip all markup processing
			// single line no-parse tag removed
			if ($detectNoparseTag)
			{
				$noparseOpen = true;
				$line = replace_bugtags($line, $noparse[2], $noparse[3], $noparse[0], $noparse[1]);
			}
			// multi-line no-parse start
			elseif ($detectNoparseTagOpen && !$noparseOpen)
			{
				$noparseOpen = true;
				$line = replace_bugtags($line, $noparse[2], PHP_EOL, $noparse[0], PHP_EOL);
			}
			// multi-line no-parse end
			elseif ($detectNoparseTagOpen && $noparseOpen)
			{
				$noparseOpen = false;
				$line = replace_bugtags($line, $noparse[3], PHP_EOL, $noparse[1], $PHP_EOL);
			}

			// line is safe to parse
			if (!$noparseOpen)
			{

				// single line <blockquote>
				$detectBlockquoteTag = extract_text_from_tags($line, $blockquote[2], $blockquote[3]);
				// multiline <blockquote>
				$detectBlockquoteTagOpen = tag_exists($line, $blockquote[2]);
				$detectBlockquoteTagClose = tag_exists($line, $blockquote[3]);

				// single line <code>
				$detectCodeTag = extract_text_from_tags($line, $code[2], $code[3]);
				// multiline <code> 
				$detectCodeTagOpen = tag_exists($line, $code[2]);
				$detectCodeTagClose = tag_exists($line, $code[3]);

				// single line <pre>
				$detectPreTag = extract_text_from_tags($line, $pre[2], $pre[3]);
				// multiline <pre>
				$detectPreTagOpen = tag_exists($line, $pre[2]);
				$detectPreTagClose = tag_exists($line, $pre[3]);

				// preformatted & code must be parsed BEFORE blockquotes
				// to ensure that they can be wrapped around blockquoted text

				// preformattedOpen text is replaced by <pre> tags
				if ($detectPreTag)
				{
					$preformattedOpen = true;
					$line = replace_bugtags($line, $pre[2], $pre[3], $pre[0], $pre[1]);
				}
				elseif ($detectPreTagOpen && !$preformattedOpen)
				{
					$preformattedOpen = true;
					$line = replace_bugtags($line, $pre[2], PHP_EOL, $pre[0], PHP_EOL);
				}
				elseif ($detectPreTagClose && $preformattedOpen)
				{
					$preformattedOpen = false;
					$line = replace_bugtags($line, $pre[3], PHP_EOL, $pre[1], PHP_EOL);
				}
				
				// single line code-formatted text is replaced by <code> tags
				if ($detectCodeTag)
				{
					$codeOpen = true;
					$line = replace_bugtags($line, $code[2], $code[3], $code[0], $code[1]);
				}
				// multiline code is replaced by <pre><code>
				elseif ($detectCodeTagOpen && !$codeOpen)
				{
					$codeOpen = true;
					$line = replace_bugtags($line, $code[2], PHP_EOL, $pre[0]. $code[0], PHP_EOL);
				}
				elseif ($detectCodeTagClose && $codeOpen)
				{
					$codeOpen = false;
					$line = replace_bugtags($line, $code[3], PHP_EOL, $code[1] . $pre[1], PHP_EOL);
				}
				elseif ($codeOpen)
				{
					// all lines of code must have html symbols translated to entities first
					// important: fourth argument prevents double-encoding!
					$line = htmlentities($line, ENT_QUOTES | ENT_SUBSTITUTE | ENT_HTML401, NULL, false);
				}

				if (!$codeOpen && !$preformattedOpen)
				{
					// single line blockquote
					if ($detectBlockquoteTag)
					{
						$blockquoteOpen = true;
						$line = replace_bugtags($line, $blockquote[2], $blockquote[3], $blockquote[0], $blockquote[1]);
					}
					// multiline blockquote
					elseif ($detectBlockquoteTagOpen && !$blockquoteOpen)
					{
						$blockquoteOpen = true;
						$forceCloseParagraph = true;
						$line = replace_bugtags($line, $blockquote[2], PHP_EOL, $blockquote[0], PHP_EOL);
					}
					elseif ($detectBlockquoteTagClose && $blockquoteOpen)
					{
						$blockquoteOpen = false;
						$line = replace_bugtags($line, $blockquote[3], PHP_EOL, $blockquote[1], PHP_EOL);
					}
				}

				// look for a blank line with only a newline (PHP_EOL) and turn 
				// the text in between into paragraphOpens
				// note: newline checks must use *untrimmed* line
				// and must never be added when parsing code/preformatted
				if (!$paragraphOpen && !$codeOpen && !$preformattedOpen && $line != PHP_EOL && ($blockquoteOpen || !$forceCloseParagraph))
				{
					$paragraphOpen = true;
					$parsedOutput .= "<p>";
				}
				// close paragraphs; sometimes we need to force them closed
				if ($paragraphOpen && !$codeOpen && !$preformattedOpen && ($line == PHP_EOL || $forceCloseParagraph))
				{
					$paragraphOpen = false;
					$parsedOutput .= "</p>";
				}

				// preformattedOpen & code text is never parsed for bug tags
				if (!$preformattedOpen && !$codeOpen)
					$parsedOutput .= parseLine($line);
				else
					$parsedOutput .= $line;

				// single-line cases of blockquote/pre/code are ended here
				if ($preformattedOpen && $detectPreTag)
					$preformattedOpen = false;

				if ($codeOpen && $detectCodeTag)
					$codeOpen = false;

				if ($blockquoteOpen && $detectBlockquoteTag)
					$blockquoteOpen = false;
			}
			// noparse detected, just add the line
			else
			{
				if ($noparseOpen && $detectNoparseTag)
					$noparseOpen = false;
				
				$parsedOutput .= $line;
			}
		}
	}
	// just a single line of text to process
	else
		$parsedOutput = parseLine($text);

	return $parsedOutput;
}


// escape to html numerics anything that shouldn't be parsed as a tag
function escapes_to_htmlnumerics($line)
{
	global $escapetag;
	// escape to html numerics anything that shouldn't be parsed as a tag
	do {
		$escape = extract_text_from_tags($line, $escapetag["escape"][0], $escapetag["escape"][1]);
		if ($escape)
		{
			// note: mb_encode does the char -> html magic. that gnarly array just covers as much of the character set as possible using a bitmask
			// from: https://stackoverflow.com/questions/3005116/how-to-convert-all-characters-to-their-html-entity-equivalent-using-php
			$line = replace_tags($line, $escapetag["escape"][0], $escapetag["escape"][1], mb_encode_numericentity($escape, array(0x0, 0xffff, 0, 0xffff)));
		}
	} while ($escape != false);
	return $line;
}

// parses a single line of text
function parseLine($line)
{
	global $tags, $linktag, $imagetag, $hrtag, $tabsymbol;
	extract($tags);

	// loop through the string until no more tags are detected
	do
	{
		// store a copy before modifying
		$unmodifiedString = $line;

		// process any html escapes before the line is parsed for tags
		$line = escapes_to_htmlnumerics($line);

		// any tabs are converted into whitespaces.
		$line = str_replace($tabsymbol["tab"][1], $tabsymbol["tab"][0], $line);

		// add horizontal rule when present
		$line = str_replace($hrtag["hr"][1], $hrtag["hr"][0], $line);

		// image tag must be parsed before links, since bug's default #[]{} uses a link tag
		do {
			$image = extract_text_from_tags($line, $imagetag["url"][0], $imagetag["url"][1]);
			if ($image)
			{
				$imageAlt = extract_text_from_tags($line, $imagetag["name"][0], $imagetag["name"][1]);
				$image = '<img src="' . $image . '" alt="' . $imageAlt . '" title ="' . $imageAlt . '">';
				$line = replace_tags($line, $imagetag["url"][0], $imagetag["url"][1], $image);
				$line = replace_tags($line, $imagetag["name"][0], $imagetag["name"][1], '');
			}
		} while ($image != false);

		// parse link tag
		// special processing done here, as links can be remote or local
		do {
			$link = extract_text_from_tags($line, $linktag["url"][0], $linktag["url"][1]);
			if ($link)
			{
				$linktitle = extract_text_from_tags($line, $linktag["name"][0], $linktag["name"][1]);

				// split up the link into its constituent parts, so we can figure out if it's local or remote
				$linkPieces = count(explode('.', $link));
				// a remote link has a domain and TLD
				if ($linkPieces > 1)
				{
					global $url_protocol;
					// if the user forgot the protocol in the link, add it back in
					$checkurlhttp = strpos($link, ":");
					// note the triple-equals here!
					if ($checkurlhttp === false)
						$prefix = $url_protocol;
					else
						$prefix = "";

					$link = '<a href="' . $prefix . $link . '">' . $linktitle . '</a>';
				}
				// local links are a kiki-specific quality of life feature
				elseif (function_exists("build_local_permalink"))
					$link = build_local_permalink($link, $linktitle);

				$line = replace_tags($line, $linktag["url"][0], $linktag["url"][1], $link);
				$line = replace_tags($line, $linktag["name"][0], $linktag["name"][1], '');
			}
		} while ($link != false);

		// all simple <tag></tag> pairs processed here
		foreach ($tags as $tag)
		{
			// following the tag format of tagname:<tag>:</tag>:start_symbol:end_symbol
			$line = replace_bugtags($line, $tag[2], $tag[3], $tag[0], $tag[1]);
		}

		// add line breaks to any line that has an EOL
		// BUT prevent line breaks after h1-h6 tags (which automatically add a line break in the html spec)
		if (strpos($line, "</h1>") !== false && strpos($line, "</h2>") !== false &&
			strpos($line, "</h3>") !== false && strpos($line, "</h4>") !== false &&
			strpos($line, "</h5>") !== false && strpos($line, "</h6>") !== false)
			$addBreak = false;
		else
			$addBreak = true;

	} while ($unmodifiedString !== $line);

	// return final output
	return $line;
}

// replaces text between $starttag and $endtag
// used primarily for replacing link tags with URLs
function replace_tags($inputString, $starttag, $endtag, $replacementText)
{
	$substring_start = strpos($inputString, $starttag);
	// start tag found
	if ($substring_start !== false)
	{
			// the start of the tagged text is after the tag's width
			$substring_start += strlen($starttag);
			$substring_length = strpos($inputString, $endtag, $substring_start);
			if ($substring_length)
				$substring_length = $substring_length - $substring_start;
			// end tag found
			if ($substring_length !== false)
			{
				// extract out the words between the tags
				$parsedString = substr($inputString, $substring_start, $substring_length);
				// now glue the entire line back together, with the tags inserted
				$firstHalfInputString = substr($inputString, 0, $substring_start - strlen($starttag));
				$secondHalfInputString = substr($inputString, $substring_start + strlen($parsedString) + strlen($endtag));
				$replacedText = $firstHalfInputString . $replacementText . $secondHalfInputString;
				return $replacedText;
			}
	}
	// no tags found
	return $inputString;
}

// extracts text from $inputString between $starttag and $endtag
// used primarily for extracting titles and urls from links
function extract_text_from_tags($inputString, $starttag, $endtag)
{
	$inputString = trim($inputString, " \t\v\x00");
	$substring_start = strpos($inputString, $starttag);
	if ($substring_start !== false)
	{
		$substring_start += strlen($starttag);
		$substring_length = strpos($inputString, $endtag, $substring_start);
		if ($substring_length)
			$substring_length = $substring_length - $substring_start;
		// found the end tag
		if ($substring_length !== false)
		{
			$extractedString = substr($inputString, $substring_start, $substring_length);
			return $extractedString;
		}
	}
	// no tags, return false
	return false;
}

// This function searches a supplied $inputString for $startbugtag and $endbugtag.
// if BOTH tags are found, it replaces each bug-tag with the html $openhtmltag and $closehtmltag;
// and returns an html-formatted string
function replace_bugtags($inputString, $startbugtag, $endbugtag, $openhtmltag, $closehtmltag = PHP_EOL)
{
	$inputString = trim($inputString, " \t\v\x00");
	$substring_start = strpos($inputString, $startbugtag);
	// start tag found
	// holy fucking mother of god: != is NOT the same as !==
	// if you use a simple ($substring_start) here to check for true,
	// it will fail to capture conditions where the startbugtag started at index 0
	// never, ever, screw with the way this line is written!
	if ($substring_start !== false)
	{
		// the start of the tagged text is after the tag's width
		$substring_start += strlen($startbugtag);
		$substring_length = strpos($inputString, $endbugtag, $substring_start);
		//
		if ($substring_length)
			$substring_length = $substring_length - $substring_start;
		// end tag found
		if ($substring_length !== false)
		{
			// extract out the words between the tags
			$parsedString = substr($inputString, $substring_start, $substring_length);
			// now glue the entire line back together, with the tags inserted
			$firstHalfInputString = substr($inputString, 0, $substring_start - strlen($startbugtag));
			$secondHalfInputString = substr($inputString, $substring_start + strlen($parsedString) + strlen($endbugtag));
			$parsedString = $firstHalfInputString . $openhtmltag . $parsedString . $closehtmltag . $secondHalfInputString;
			return $parsedString;
		}
	}
	// no tags found
	return $inputString;
}

// checks for the existence of one specific tag
// returns true if one tag exists
function tag_exists($line, $firstTag)
{
	if (trim($line) == $firstTag || strlen(extract_text_from_tags($line, $firstTag, PHP_EOL)))
		return true;
	else
		return false;
}

// returns any tags critical to bug's operation as an associative array
// special markup tags necessary to process markup
// these are unfortunately hardcoded here because
// they allow the scripting language to get itself off the ground
// (it's a chicken-egg problem for any scripting language)
// so cannot be set in tags.bug
function get_basic_script_tags()
{
	$basictags = [];
	$basictags["array"][0] = "((";
	$basictags["array"][1] = "))";
	$basictags["comment"] = "//";
	return $basictags;
}

// reads the bug syntax symbols from a bug-formatted text file,
// and returns an array that carries all of the symbols
function extract_bug_symbols()
{
	$bug_tags_file = dirname(__FILE__) . "/tags.bug";
	// load array and comment tags so we can start processing a bug file
	$scripttags = get_basic_script_tags();

	$sourceText = file($bug_tags_file);
	if ($sourceText)
	{
		// when true, insert values into a new array
		$build_array = false;
		$current_array = [];
		$current_key = "";
		foreach ($sourceText as $line)
		{
			$line_start = trim($line);

			// look for comments and ignore that line
			if (strpos($line_start, $scripttags["comment"]) !== false)
				continue;

			// check for an array definition
			// arrays are defined like this: 
			// ((arrayname))
			// keyname:value:value:value
			$array_start_key = extract_text_from_tags($line_start, $scripttags["array"][0], $scripttags["array"][1]);
			if ($array_start_key != "")
			{
				$build_array = true;
				$current_key = $array_start_key;
				$current_array[$current_key] = [];
				continue;
			}
			// check for the array end marker key which is an empty line
			if (strpos($line, PHP_EOL) === 0)
			{
				$build_array = false;
				$current_key = "";
				continue;
			}

			$line_symbols = explode(':', $line);

			if ($line_symbols)
			{
				// the first symbol should be extracted and used as the
				// key for the entire array, then removed from line_symbols
				$line_key = $line_symbols[0];
				array_splice($line_symbols,0,1);
				// now build the array from the list of values
				foreach ($line_symbols as $key=>$symbol)
				{
					if ($build_array)
						// do NOT trim tabs, because it's used as a tag!
						$current_array[$current_key][$line_key][$key] = trim($symbol, " \r\n\v\x00");
				}
			}
		}
		return $current_array;
	}
}

// replaces any newline characters with the PHP_EOL character
// which is specific to the architecture of the server
// this allows windows/mac/linux/DOS users to create pages
// that auto-convert to the server's newline
// $text: a string or array of strings
// returns $text (array or string) with newline replacements
function convertNewline($text)	
{
	// unfortunately, we can't rely upon str_replace for this
	// function and must unroll the entire array, trim it,
	// and force-add the correct line-ending.
	$newlineChars = "\n\r";
	if (is_array($text))
	{
		$replacedLines = [];
		foreach ($text as $line)
		{
			$replacedLines[] = trim($line, $newlineChars) . PHP_EOL;
		}
		return $replacedLines;
	}
	else
	{
		$replacedLine = trim($text, $newlineChars) . PHP_EOL;
		return $replacedLine;
	}
}

